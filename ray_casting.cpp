#include <iostream>
#include <cmath>

// マップをつくる（まわりがかべで、なかはからっぽ）
char ちず[16][17] = {
    "################",
    "#              #",
    "#              #",
    "#   ########   #",
    "#   #      #   #",
    "#   #      #   #",
    "#   ########   #",
    "#              #",
    "#              #",
    "################",
    "#              #",
    "#              #",
    "#              #",
    "#              #",
    "#              #",
    "################"};

int main()
{
    // まっすぐみているばしょ（ちずのまんなか）
    float いち_x = 8, いち_y = 8;

    // みぎからひだりに30ほんのビームをだす
    for (int ビームばんごう = 0; ビームばんごう < 30; ビームばんごう++)
    {
        // ビームのかくど（すこしずつずらす）
        float かくど = -0.5f + ビームばんごう / 30.0f;

        // ビームのいちとすすむりょう
        float ビーム_x = いち_x, ビーム_y = いち_y;
        float はば = cos(かくど) * 0.1f;
        float たかさ = sin(かくど) * 0.1f;
        float きょり = 0;

        // ビームをすこしずつのばして、かべにあたるまでつづける
        while (きょり < 16)
        {
            ビーム_x += はば;
            ビーム_y += たかさ;
            きょり += 0.1f;

            if (ちず[(int)ビーム_y][(int)ビーム_x] == '#')
            {
                break; // かべにあたった！
            }
        }

        // かべまでのきょりで、かべのたかさをきめる
        int かべのたかさ = 15 / (きょり + 0.1f);

        // うえからしたまで、1れつのえをかく
        for (int たて = 0; たて < 15; たて++)
        {
            if (たて < 7 - かべのたかさ / 2)
            {
                std::cout << '.'; // そら
            }
            else if (たて < 7 + かべのたかさ / 2)
            {
                std::cout << '|'; // かべ
            }
            else
            {
                std::cout << ' '; // ゆか
            }
        }

        // 1れつおわったら、つぎのビームへ
        std::cout << "\n";
    }

    return 0;
}
